def plot_targets_vs_achieved_6d(
    task_config,
    targets,
    new_elites,
    generation: int,
    iteration: int,
    output_dir,
    pairs=None,
) -> None:
    """6-D analogue of ``plot_targets_vs_achieved``.

    Renders a grid of 2-D projections (one subplot per pair from *pairs*).
    Falls back silently on any error so it never blocks training.
    """
    try:
        import matplotlib.pyplot as plt
        plt.switch_backend('Agg')

        dims = task_config.dimensions
        n_dims = len(dims)
        if n_dims < 2:
            return

        pairs = pairs or _6D_DEFAULT_PAIRS
        # Filter pairs to valid indices
        pairs = [(ix, iy) for ix, iy in pairs if ix < n_dims and iy < n_dims]
        if not pairs:
            return

        n_pairs = len(pairs)
        ncols = min(3, n_pairs)
        nrows = (n_pairs + ncols - 1) // ncols

        fig, axes = plt.subplots(nrows, ncols, figsize=(5 * ncols, 4 * nrows), squeeze=False)
        fig.suptitle(f"Targets vs Achieved (6D) — Gen {generation} Iter {iteration}", fontsize=10)

        # Build arrays
        target_pts = np.array([[t[d.name] for d in dims] for t in targets]) if targets else np.empty((0, n_dims))
        elite_pts, elite_sources = [], []
        for e in new_elites:
            elite_pts.append([e.task_metrics[d.name] for d in dims])
            elite_sources.append(getattr(e, 'source', ''))
        elite_pts = np.array(elite_pts) if elite_pts else np.empty((0, n_dims))
        is_diffusion = np.array(['diffusion' in s for s in elite_sources], dtype=bool)

        for ax_idx, (ix, iy) in enumerate(pairs):
            ax = axes[ax_idx // ncols][ax_idx % ncols]

            if len(target_pts):
                _scatter_2d_projection(ax, target_pts, ix, iy, dims,
                                       c='steelblue', s=20, alpha=0.3,
                                       label='Targets', zorder=1)
            if len(elite_pts):
                if np.any(~is_diffusion):
                    _scatter_2d_projection(ax, elite_pts[~is_diffusion], ix, iy, dims,
                                           c='red', s=60, alpha=0.8,
                                           label='New Elites', marker='*', zorder=3)
                if np.any(is_diffusion):
                    _scatter_2d_projection(ax, elite_pts[is_diffusion], ix, iy, dims,
                                           c='purple', s=40, alpha=0.8,
                                           label='New Elites (Diff)', marker='D', zorder=4)
            ax.legend(fontsize=6, loc='upper right')

        # Hide unused axes
        for ax_idx in range(n_pairs, nrows * ncols):
            axes[ax_idx // ncols][ax_idx % ncols].set_visible(False)

        fig.tight_layout()
        plot_path = Path(output_dir) / "targets_vs_achieved_6d.png"
        fig.savefig(str(plot_path), dpi=120)
        plt.close(fig)
    except Exception as e:
        print(f"[WARN] Failed to plot 6d targets vs achieved: {e}")


def plot_curriculum_6d(
    task_config,
    bin_centers: "np.ndarray",
    refine_mask: "np.ndarray",
    explore_mask: "np.ndarray",
    frontier_mask: "np.ndarray",
    elite_points: "np.ndarray",
    elite_sources,
    output_plot_path: str,
    pairs=None,
) -> None:
    """6-D analogue of the inline frontier curriculum plot in ``get_target_values``.

    Renders curriculum zone scatter plots as a grid of 2-D projections.
    All arguments mirror what is already computed inside ``get_target_values``.
    """
    try:
        import matplotlib.pyplot as plt
        plt.switch_backend('Agg')

        dims = task_config.dimensions
        n_dims = len(dims)
        if n_dims < 2:
            return

        pairs = pairs or _6D_DEFAULT_PAIRS
        pairs = [(ix, iy) for ix, iy in pairs if ix < n_dims and iy < n_dims]
        if not pairs:
            return

        n_pairs = len(pairs)
        ncols = min(3, n_pairs)
        nrows = (n_pairs + ncols - 1) // ncols

        fig, axes = plt.subplots(nrows, ncols, figsize=(5 * ncols, 4 * nrows), squeeze=False)
        fig.suptitle("Curriculum Zones (6D projections)", fontsize=10)

        is_diffusion = np.array(['diffusion' in str(s) for s in elite_sources], dtype=bool)

        for ax_idx, (ix, iy) in enumerate(pairs):
            ax = axes[ax_idx // ncols][ax_idx % ncols]

            if frontier_mask.any():
                ax.scatter(bin_centers[frontier_mask, ix], bin_centers[frontier_mask, iy],
                           c='lightgray', marker='s', s=30, alpha=0.2, label='Frontier', zorder=1)
            if explore_mask.any():
                ax.scatter(bin_centers[explore_mask, ix], bin_centers[explore_mask, iy],
                           c='skyblue', marker='s', s=30, alpha=0.5, label='Explore', zorder=2)
            if refine_mask.any():
                ax.scatter(bin_centers[refine_mask, ix], bin_centers[refine_mask, iy],
                           c='lightgreen', marker='s', s=30, alpha=0.3, label='Refine', zorder=3)

            if len(elite_points):
                if np.any(~is_diffusion):
                    ax.scatter(elite_points[~is_diffusion, ix], elite_points[~is_diffusion, iy],
                               c='black', s=15, marker='x', label='Elites', zorder=5)
                if np.any(is_diffusion):
                    ax.scatter(elite_points[is_diffusion, ix], elite_points[is_diffusion, iy],
                               c='red', s=20, marker='D', label='Diffusion', zorder=6)

            ax.set_xlabel(dims[ix].name, fontsize=7)
            ax.set_ylabel(dims[iy].name, fontsize=7)
            ax.set_xlim(dims[ix].min_val, dims[ix].max_val)
            ax.set_ylim(dims[iy].min_val, dims[iy].max_val)
            ax.tick_params(labelsize=6)
            ax.grid(True, alpha=0.25)
            ax.legend(fontsize=6, loc='upper right')

        for ax_idx in range(n_pairs, nrows * ncols):
            axes[ax_idx // ncols][ax_idx % ncols].set_visible(False)

        fig.tight_layout()
        fig.savefig(output_plot_path, dpi=120)
        plt.close(fig)
    except Exception as e:
        print(f"[WARN] Failed to plot 6d curriculum: {e}")


def plot_archive_6d(
    task_config,
    archive: "EliteArchive",
    output_path,
    pairs=None,
    title: str = "Archive (6D projections)",
) -> None:
    """Scatter plot of all archive elites across 6-D projection pairs.

    Can be called standalone (e.g. from run_single_iteration.py) to inspect
    the current state of a 6D archive without running a full generation.
    """
    try:
        import matplotlib.pyplot as plt
        plt.switch_backend('Agg')

        dims = task_config.dimensions
        n_dims = len(dims)
        if n_dims < 2:
            return

        pairs = pairs or _6D_DEFAULT_PAIRS
        pairs = [(ix, iy) for ix, iy in pairs if ix < n_dims and iy < n_dims]
        if not pairs:
            return

        elites = list(archive.values())
        if not elites:
            return

        all_pts = np.array([[e.task_metrics[d.name] for d in dims] for e in elites])
        sources = [getattr(e, 'source', '') for e in elites]
        is_diffusion = np.array(['diffusion' in s for s in sources], dtype=bool)
        fitness = np.array([e.fitness for e in elites])

        n_pairs = len(pairs)
        ncols = min(3, n_pairs)
        nrows = (n_pairs + ncols - 1) // ncols

        fig, axes = plt.subplots(nrows, ncols, figsize=(5 * ncols, 4 * nrows), squeeze=False)
        fig.suptitle(f"{title} — {len(elites)} elites", fontsize=10)

        for ax_idx, (ix, iy) in enumerate(pairs):
            ax = axes[ax_idx // ncols][ax_idx % ncols]

            sc = ax.scatter(all_pts[:, ix], all_pts[:, iy],
                            c=fitness, cmap='viridis', s=25, alpha=0.7, zorder=2)
            ax.set_xlabel(dims[ix].name, fontsize=7)
            ax.set_ylabel(dims[iy].name, fontsize=7)
            ax.set_xlim(dims[ix].min_val, dims[ix].max_val)
            ax.set_ylim(dims[iy].min_val, dims[iy].max_val)
            ax.tick_params(labelsize=6)
            ax.grid(True, alpha=0.25)
            fig.colorbar(sc, ax=ax, shrink=0.8, label='fitness' if ax_idx == 0 else '')

        for ax_idx in range(n_pairs, nrows * ncols):
            axes[ax_idx // ncols][ax_idx % ncols].set_visible(False)

        fig.tight_layout()
        fig.savefig(str(output_path), dpi=120)
        plt.close(fig)
    except Exception as e:
        print(f"[WARN] Failed to plot 6d archive: {e}")

